import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const hash = data => createHash('sha256').update(data).digest('hex');
const kebab = value => value.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`);
const literal = value => JSON.stringify(value);
const rem = value => `${value / 16}rem`;
export function validateManifest(m) {
  if (m.version !== 1 || m.rootSize !== 16) throw new Error('Unsupported typography manifest');
  for (const [name, font] of Object.entries(m.families)) {
    if (!font.name || !(font.minWeight <= font.maxWeight)) throw new Error(`Invalid font ${name}`);
  }
  for (const [name, size] of Object.entries(m.sizes)) {
    if (!Number.isFinite(size) || size <= 0) throw new Error(`Invalid size ${name}`);
  }
  for (const [name, style] of Object.entries({...m.styles, ...m.presets})) {
    const font = m.families[style.family];
    if (!font || !Number.isFinite(style.size) || style.size <= 0 || style.weight < font.minWeight || style.weight > font.maxWeight || !(style.lineHeight > 0) || !Number.isFinite(style.tracking ?? 0)) throw new Error(`Invalid style ${name}`);
  }
  if (!/^[a-f0-9]{64}$/.test(m.asset.sha256)) throw new Error('Missing font provenance hash');
  return m;
}

export function generateWeb(m) {
  validateManifest(m);
  const families = {
    body: 'var(--font-space-grotesk, "Space Grotesk"), "Space Grotesk", system-ui, sans-serif',
    display: 'var(--font-orbitron, "Orbitron"), "Orbitron", var(--font-space-grotesk, "Space Grotesk"), system-ui, sans-serif',
    mono: 'ui-monospace, "SFMono-Regular", monospace',
  };
  const vars = Object.entries(families).map(([key, value]) => `  --ds-font-${key}: ${value};`);
  for (const [key, value] of Object.entries(m.scale)) vars.push(`  --ds-text-${key}: ${rem(value)};`);
  for (const [key, value] of Object.entries(m.sizes)) vars.push(`  --ds-size-${kebab(key)}: ${rem(value)};`, `  --ds-canvas-${kebab(key)}: ${value}px;`);
  for (const [key, value] of Object.entries(m.weights)) vars.push(`  --ds-weight-${key}: ${value};`);
  for (const [key, value] of Object.entries(m.leading)) vars.push(`  --ds-leading-${key}: ${value};`);
  for (const [key, value] of Object.entries(m.tracking)) vars.push(`  --ds-tracking-${key}: ${value}em;`);
  vars.push('  --ds-numeric-tabular: "tnum" 1;');
  for (const [key, s] of Object.entries(m.styles)) {
    const prefix = `--ds-type-${kebab(key)}`;
    vars.push(`  ${prefix}-family: var(--ds-font-${s.family});`, `  ${prefix}-size: ${rem(s.size)};`, `  ${prefix}-weight: ${s.weight};`, `  ${prefix}-leading: ${s.lineHeight};`, `  ${prefix}-tracking: ${(s.tracking ?? 0) / s.size}em;`);
  }
  const css = `  /* BEGIN GENERATED TYPOGRAPHY */\n${vars.join('\n')}\n  /* END GENERATED TYPOGRAPHY */`;
  const roles = Object.fromEntries(Object.entries({...m.styles, ...m.presets}).map(([name, s]) => [name, { fontFamily: families[s.family], fontSize: rem(s.size), fontWeight: s.weight, lineHeight: s.lineHeight, letterSpacing: `${s.tracking / s.size}em` }]));
  const ts = `// Generated by typography-library.mjs. Edit the typography manifest.\nexport const typography = ${JSON.stringify({ version: m.version, family: families, size: Object.fromEntries(Object.entries(m.scale).map(([k,v])=>[k,rem(v)])), sizePx: m.sizes, sizeRem: Object.fromEntries(Object.entries(m.sizes).map(([k,v])=>[k,rem(v)])), weight: m.weights, lineHeight: m.leading, letterSpacing: Object.fromEntries(Object.entries(m.tracking).map(([k,v])=>[k,`${v}em`])), numeric: {tabular:'"tnum" 1'}, styles: roles, presets: m.presets }, null, 2)} as const;\nexport type TypographyTokens = typeof typography;\nexport type TextRole = keyof typeof typography.styles;\nexport const textStyle = (role: TextRole) => typography.styles[role];\nexport const bodyWeight = (weight: number) => Math.min(700, Math.max(300, weight));\n`;
  const classes = Object.keys({...m.styles, ...m.presets}).map(name => {
    const prefix = `--ds-type-${kebab(name)}`;
    return `.ds-type-${kebab(name)}{font-family:var(${prefix}-family);font-size:var(${prefix}-size);font-weight:var(${prefix}-weight);line-height:var(${prefix}-leading);letter-spacing:var(${prefix}-tracking)}`;
  }).join('\n');
  return { css, ts, classes };
}

export function generateDart(m) {
  validateManifest(m);
  const styles = Object.entries({...m.styles, ...m.presets}).map(([name,s])=>`  static const ${name} = TextStyle(fontFamily: ${s.family}Font, fontSize: ${s.size}, fontWeight: FontWeight.w${s.weight}, height: ${s.lineHeight}, letterSpacing: ${s.tracking ?? 0});`).join('\n');
  const themes = Object.entries(m.material).map(([key,role])=>`    ${key}: ${role},`).join('\n');
  return `// Generated by typography-library.mjs. Edit the canonical manifest in Designer.\nimport 'package:flutter/material.dart';\n\nabstract final class StatOzTypography {\n  static const version = ${m.version};\n  static const bodyFont = ${literal(m.families.body.name)};\n  static const displayFont = ${literal(m.families.display.name)};\n${Object.entries(m.sizes).map(([k,v])=>`  static const ${k} = ${v}.0;`.replace(/(\d+\.\d+)\.0;/, '$1;')).join('\n')}\n${Object.entries(m.weights).map(([k,v])=>`  static const ${k} = FontWeight.w${v};`).join('\n')}\n${styles}\n  static const textTheme = TextTheme(\n${themes}\n  );\n  static FontWeight bodyWeight(FontWeight value) => FontWeight.values[(value.value ~/ 100 - 1).clamp(2, 6)];\n  static TextStyle bodyAt(double size, {FontWeight weight = medium, double height = 1.4, double letterSpacing = 0}) => body.copyWith(fontSize: size, fontWeight: bodyWeight(weight), height: height, letterSpacing: letterSpacing);\n  static TextStyle displayAt(double size, {FontWeight weight = black, double height = 1, double letterSpacing = 1.5}) => display.copyWith(fontSize: size, fontWeight: weight, height: height, letterSpacing: letterSpacing);\n}\n`;
}

export async function synchronize(root, { check = false } = {}) {
  root = path.resolve(root);
  const flutter = await fs.access(path.join(root, 'pubspec.yaml')).then(()=>true,()=>false);
  const manifestPath = flutter ? 'design-system/typography/manifest.json' : 'src/design-system/typography/manifest.json';
  const raw = await fs.readFile(path.join(root, manifestPath));
  const m = validateManifest(JSON.parse(raw));
  const web = generateWeb(m);
  const font = await fs.readFile(path.join(root, flutter ? 'assets/fonts/SpaceGrotesk-VariableFont_wght.ttf' : 'src/app/fonts/space-grotesk-variable.ttf'));
  if (hash(font) !== m.asset.sha256) throw new Error(`Font checksum differs: ${root}`);
  const license = await fs.readFile(path.join(root, flutter ? 'assets/fonts/SpaceGrotesk-OFL.txt' : 'src/app/fonts/space-grotesk-OFL.txt'));
  // The OFL is text, so verify canonical line endings rather than the
  // checkout-specific byte representation.
  if (hash(license.toString('utf8').replace(/\r\n/g, '\n')) !== m.asset.licenseSha256) throw new Error(`Font license checksum differs: ${root}`);
  const files = flutter ? { 'lib/design_system/typography.dart': generateDart(m) } : {
    'src/design-system/tokens/typography.ts': web.ts,
    'src/design-system/styles/typography.css': `${web.classes}\n`,
    'src/design-system/typography/typography.dart': generateDart(m),
  };
  if (!flutter) {
    const file = 'src/design-system/styles/tokens.css';
    const old = await fs.readFile(path.join(root, file), 'utf8');
    const normalized = old.replace(/\r\n/g,'\n');
    if (normalized.includes('/* BEGIN GENERATED TYPOGRAPHY */')) {
      files[file] = normalized.replace(/  \/\* BEGIN GENERATED TYPOGRAPHY \*\/[\s\S]*?  \/\* END GENERATED TYPOGRAPHY \*\//, web.css);
    } else {
      if (!/  \/\* Typography \*\/[\s\S]*?\n}/.test(normalized)) throw new Error('Cannot locate typography token section');
      files[file] = normalized.replace(/  \/\* Typography \*\/[\s\S]*?(?=\n})/, web.css);
    }
    const classes = `/* BEGIN GENERATED TEXT STYLES */\n${web.classes}\n/* END GENERATED TEXT STYLES */`;
    files[file] = files[file].includes('/* BEGIN GENERATED TEXT STYLES */')
      ? files[file].replace(/\/\* BEGIN GENERATED TEXT STYLES \*\/[\s\S]*?\/\* END GENERATED TEXT STYLES \*\//, classes)
      : `${files[file].trimEnd()}\n\n${classes}\n`;
  }
  for (const [file, content] of Object.entries(files)) {
    const target = path.join(root, file);
    const previous = await fs.readFile(target, 'utf8').catch(()=>null);
    if (previous?.replace(/\r\n/g,'\n') === content) continue;
    if (check) throw new Error(`Stale typography: ${target}. Run typography:sync.`);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, content);
  }
  return hash(raw);
}

async function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const check = process.argv.includes('--check');
  if (process.argv.includes('--all')) {
    const pkg = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
    if (pkg.name !== 'statoz-designer') throw new Error('--all must run from the canonical Designer library');
    // Only this explicitly requested mode writes neighboring checkouts.
    const web = path.resolve(root, '../statoz_web');
    const flutter = path.resolve(root, '../flutter_projects/card_game');
    const source = 'src/design-system/typography/manifest.json';
    for (const [target, flutterTarget] of [[web, false], [flutter, true]]) {
      await fs.access(path.join(target, flutterTarget ? 'pubspec.yaml' : 'package.json'));
      const copies = [[source, flutterTarget ? 'design-system/typography/manifest.json' : source], ['src/app/fonts/space-grotesk-variable.ttf', flutterTarget ? 'assets/fonts/SpaceGrotesk-VariableFont_wght.ttf' : 'src/app/fonts/space-grotesk-variable.ttf'], ['src/app/fonts/space-grotesk-OFL.txt', flutterTarget ? 'assets/fonts/SpaceGrotesk-OFL.txt' : 'src/app/fonts/space-grotesk-OFL.txt'], ['scripts/typography-library.mjs', 'scripts/typography-library.mjs']];
      for (const [from, to] of copies) {
        const bytes = await fs.readFile(path.join(root, from));
        const destination = path.join(target, to);
        const previous = await fs.readFile(destination).catch(()=>null);
        if (previous?.equals(bytes)) continue;
        if (check) throw new Error(`Typography snapshot differs: ${destination}`);
        await fs.mkdir(path.dirname(destination), { recursive: true });
        await fs.writeFile(destination, bytes);
      }
      await synchronize(target, { check });
    }
  }
  await synchronize(root, { check });
  console.log(`Typography ${check ? 'verified' : 'generated'}${process.argv.includes('--all') ? ' across all platforms' : ' locally'}.`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
