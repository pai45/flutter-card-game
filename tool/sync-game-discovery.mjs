import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

export function generate(source, flutterRoot, webRoot) {
  const manifestText=fs.readFileSync(path.join(source,'manifest.json'),'utf8');
  const manifest=JSON.parse(manifestText);
  if(manifest.version!==1||manifest.width!==220||manifest.height!==160||Object.keys(manifest.games).length!==18)throw Error('Invalid discovery family manifest');
  const files=new Map();
  const put=(root,name,body)=>{if(root)files.set(path.join(root,name),body);};
  const hash=crypto.createHash('sha256').update(manifestText);
  const scenes={};
  for(const [id,game] of Object.entries(manifest.games)) {
    const svg=fs.readFileSync(path.join(source,'masters',`${id}.svg`),'utf8');
    if(/<script|<image|foreignObject|href=|<text|url\(/i.test(svg))throw Error(`Unsupported or external artwork: ${id}`);
    hash.update(svg);
    const layers=[...svg.matchAll(/<g data-layer="([a-z]+)">([\s\S]*?)<\/g><!-- end-layer -->/g)];
    if(layers.length!==game.layers.length)throw Error(`Layer mismatch: ${id}`);
    scenes[id]={...game,layers:layers.map(([,_id,body],i)=>{
      if(_id!==game.layers[i].id)throw Error(`Layer order mismatch: ${id}`);
      const filename=`${id}-${_id}.svg`;
      const layer=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 220 160">${body}</svg>\n`;
      put(flutterRoot,`assets/game_discovery/layers/${filename}`,layer);
      put(webRoot,`public/assets/games/discovery/${filename}`,layer);
      return {...game.layers[i],asset:filename};
    })};
    // Complete stills use exactly the same layer transforms at the still phase.
    const body=layers.map(([,,body],i)=>{
      const m=sample(game.layers[i].frames,manifest.stillPhase);
      return `<g opacity="${m.opacity}" transform="translate(${m.x} ${m.y}) translate(${game.pivot.join(' ')}) rotate(${m.rotate}) scale(${m.scale}) translate(${-game.pivot[0]} ${-game.pivot[1]})">${body}</g>`;
    }).join('');
    put(webRoot,`public/assets/games/${id}.svg`,`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 220 160"><title>${game.title}</title>${body}</svg>\n`);
    put(webRoot,`scripts/game-discovery-source/masters/${id}.svg`,svg);
  }
  const sourceHash=hash.digest('hex');
  const data={version:1,width:220,height:160,cycleMs:manifest.cycleMs,stillPhase:manifest.stillPhase,sourceHash,games:scenes};
  put(flutterRoot,'lib/widgets/cyber/game_discovery.g.dart',`// Generated by tool/sync-game-discovery.mjs. Do not edit.\nimport 'dart:convert';\nfinal Map<String, dynamic> gameDiscoveryData = jsonDecode(r'''${JSON.stringify(data)}''') as Map<String, dynamic>;\n`);
  put(flutterRoot,'lib/design_system/game_discovery_palette.g.dart',`// Generated artwork material tokens. Canonical values: assets/game_discovery/manifest.json.\nimport 'package:flutter/painting.dart';\nabstract final class GameDiscoveryPalette {\n${Object.entries(manifest.materials).map(([key,v])=>`  static const ${key} = Color(0xFF${v.slice(1).toUpperCase()});`).join('\n')}\n}\n`);
  put(webRoot,'src/features/games/components/game-discovery.generated.ts',`// Generated by scripts/sync-game-discovery.mjs. Do not edit.\nimport type { DiscoveryFamily } from './discovery-motion';\nexport const discoveryFamily: DiscoveryFamily = ${JSON.stringify(data,null,2)};\n`);
  put(webRoot,'src/design-system/tokens/game-discovery.generated.ts',`// Generated discovery identity and artwork material tokens.\nexport const discoveryAccents = ${JSON.stringify(Object.fromEntries(Object.entries(manifest.games).map(([id,g])=>[`game-${id}`,g.accent])),null,2)} as const;\nexport const discoveryMaterials = ${JSON.stringify(manifest.materials,null,2)} as const;\n`);
  put(webRoot,'src/design-system/styles/game-discovery.generated.css',`/* Generated by scripts/sync-game-discovery.mjs. */\n:root {\n${Object.entries(manifest.games).map(([id,g])=>`  --ds-color-accent-game-${id}: ${g.accent};`).join('\n')}\n${Object.entries(manifest.materials).map(([k,v])=>`  --ds-color-art-${k.replace(/[A-Z]/g,m=>'-'+m.toLowerCase())}: ${v};`).join('\n')}\n}\n`);
  put(webRoot,'scripts/game-discovery-source/manifest.json',manifestText);
  return {files,data};
}
export function sample(frames,phase) {
  const empty={x:0,y:0,rotate:0,scale:1,opacity:1};
  if(!frames.length)return empty;
  const t=Math.max(0,Math.min(1,phase));
  let end=frames.findIndex(f=>f.at>=t);if(end<0)end=frames.length-1;
  const a=frames[Math.max(0,end-1)],b=frames[end];
  const linear=b.at===a.at?0:(t-a.at)/(b.at-a.at),ease=linear*linear*(3-2*linear);
  return Object.fromEntries(Object.keys(empty).map(k=>[k,a[k]+(b[k]-a[k])*ease]));
}
export function writeOrCheck(files,check) {
  const stale=[];
  for(const [name,body] of files) {
    const old=fs.existsSync(name)?fs.readFileSync(name,'utf8'):null;
    if(old===body)continue;
    if(check)stale.push(name);else{fs.mkdirSync(path.dirname(name),{recursive:true});fs.writeFileSync(name,body);}
  }
  if(stale.length)throw Error(`Stale discovery outputs:\n${stale.join('\n')}`);
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const cwd=process.cwd(),flutter=fs.existsSync(path.join(cwd,'pubspec.yaml'));
  const arg=name=>{const i=process.argv.indexOf(name);return i<0?null:path.resolve(process.argv[i+1]);};
  const source=arg('--from')?path.join(arg('--from'),'assets/game_discovery'):path.join(cwd,flutter?'assets/game_discovery':'scripts/game-discovery-source');
  const {files}=generate(source,flutter?cwd:null,flutter?arg('--web'):cwd);
  writeOrCheck(files,process.argv.includes('--check'));
  console.log(`${process.argv.includes('--check')?'Verified':'Generated'} discovery family: 18 games, ${files.size} outputs.`);
}
